"""Inspect loader entries without interpreting a plugin's own configuration.

Harness owns the YAML dialect. Use its bundled safe YAML parser, never execute
expressions, and cache only parsing of identical input bytes in this process.
"""
from functools import lru_cache
import json
import os
import subprocess

from errors import PatchError


_PARSE = r'''
const fs = require('node:fs');
const yaml = require(process.argv[1]);
try {
  const sources = JSON.parse(fs.readFileSync(0, 'utf8'));
  process.stdout.write(JSON.stringify(sources.map(source => yaml.load(source))));
} catch (_) {
  // Configuration can contain credentials: never print source or parser errors.
  process.stderr.write('Invalid or dynamic profile YAML');
  process.exitCode = 1;
}
'''


@lru_cache(maxsize=16)
def parse_documents(executable, archive, sources):
    if sum(len(source.encode('utf-8')) for source in sources) > 1024 * 1024:
        raise PatchError('用户配置过大，未更改配置或切换补丁。')
    try:
        # Empty profiles generated by Harness often have a comment header.
        return tuple(json.loads('\n'.join(line for line in source.splitlines()
                                          if not line.lstrip().startswith('#'))) for source in sources)
    except ValueError:
        pass
    try:
        result = subprocess.run(
            [executable, '--expose-internals', '-e', _PARSE,
             archive + '/dsh/node_modules/js-yaml'],
            input=json.dumps(sources).encode('utf-8'),
            stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            env=dict(os.environ, ELECTRON_RUN_AS_NODE='1'),
            creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0), timeout=10)
        if result.returncode or len(result.stdout) > 4 * 1024 * 1024:
            raise ValueError('parser failed')
        documents = json.loads(result.stdout)
        if not isinstance(documents, list) or len(documents) != len(sources):
            raise ValueError('invalid parser response')
        return tuple(documents)
    except (OSError, subprocess.TimeoutExpired, ValueError) as exc:
        raise PatchError('无法静态读取用户 YAML 配置；动态表达式或无效配置需先在 Harness 中处理。原文件已保留。') from exc


def verify_entries(document, filename, depth=0):
    """Only loader entries and insert/group children can name plugins.

    Model/provider labels and other data inside an ordinary entry's config are
    opaque here. A disabled entry is retained for the official loader to manage.
    """
    if document is None:
        return
    if depth > 64 or not isinstance(document, list):
        raise PatchError('无法确认用户配置中的组件结构：' + filename)
    for entry in document:
        if not isinstance(entry, dict):
            raise PatchError('无法确认用户配置中的组件结构：' + filename)
        # Patch inserts are siblings of the targeted entry, not its children.
        if 'insert' in entry:
            verify_entries(entry['insert'], filename, depth + 1)
        if entry.get('disabled') is True:
            continue
        name = entry.get('name')
        if name is not None and (not isinstance(name, str) or not name.startswith('@deepseek-ai/')):
            raise PatchError('用户 YAML 中仍有启用的额外组件，请先在 Harness 中停用：' + filename)
        if entry.get('group'):
            verify_entries(entry.get('config', []), filename, depth + 1)
